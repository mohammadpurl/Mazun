create table if not exists public.garments (
  id         bigint generated by default as identity primary key,
  name_fa    text,
  name_ar    text,
  name_en    text,
  price      numeric default 0,
  sizes      jsonb   default '[]'::jsonb,   -- [{"n":"S","ok":true}, ...]
  front      text,
  back       text,
  chart      jsonb,                         -- {"S":{"bust":92,"waist":80,"hips":98,"length":140}, ...}
  lead_days  int     default 0,             -- extra preparation days for this garment
  sort       int     default 0,
  created_at timestamptz default now()
);

alter table public.garments enable row level security;

-- everyone can read the catalogue; only a signed-in admin can change it
drop policy if exists "garments read"  on public.garments;
drop policy if exists "garments write" on public.garments;
create policy "garments read"  on public.garments for select using (true);
create policy "garments write" on public.garments for all
  using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

-- public image bucket
insert into storage.buckets (id, name, public) values ('garments', 'garments', true)
on conflict (id) do nothing;

drop policy if exists "garment images read"  on storage.objects;
drop policy if exists "garment images write" on storage.objects;
create policy "garment images read"  on storage.objects for select using (bucket_id = 'garments');
create policy "garment images write" on storage.objects for all
  using (bucket_id = 'garments' and auth.role() = 'authenticated')
  with check (bucket_id = 'garments' and auth.role() = 'authenticated');
