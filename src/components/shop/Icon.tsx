/* The shop's icon set: Phosphor glyphs drawn as inline SVG, so nothing is loaded from an icon font or from Google.
   Only the icons and weights in use are shipped (glyphs.ts, generated by scripts/icons.mjs). Light is the house
   weight; duotone marks accent chips and active states. */
import type { CSSProperties } from 'react';
import { GLYPHS, type Glyph, type Shape } from './glyphs';

/** Shapes the set lacks, drawn on the same 256 grid with Phosphor's stroke widths (12 light, 16 duotone): a dress
 *  form (head, neck, bodice, pole, base) and a shayla (the hood round the face and its two falling ends). `area` is
 *  outlined and, in duotone, tinted; `lines` are outlined only. */
const CUSTOM = {
  form: {
    area: 'M84 68H172Q190 68 186 86L166 124Q160 146 178 176H78Q96 146 90 124L70 86Q66 68 84 68Z',
    lines: 'M128 24A16 16 0 1 1 128 56A16 16 0 1 1 128 24ZM128 56V68M128 176V224M80 224H176',
  },
  scarf: {
    area: 'M72 132C64 64 192 64 184 132Q128 158 72 132Z',
    lines: 'M72 132C74 170 84 204 98 228M184 132C186 162 180 190 166 214M104 120Q128 98 152 120',
  },
};

type G = typeof GLYPHS;
export type IconName = keyof G | keyof typeof CUSTOM;
/** Icons that also ship a duotone weight; only these take weight="duotone". */
export type DuoIconName = { [K in keyof G]: G[K] extends { duotone: Shape } ? K : never }[keyof G] | keyof typeof CUSTOM;
export type IconWeight = 'light' | 'duotone';

/** Icons that point along the reading direction, so they mirror in right-to-left. */
const DIRECTIONAL = new Set<IconName>(['back', 'caret', 'external', 'next', 'send', 'swipe']);

function Drawn({ name, duo }: { name: keyof typeof CUSTOM; duo: boolean }) {
  const { area, lines } = CUSTOM[name];
  const line = { fill: 'none', stroke: 'currentColor', strokeWidth: duo ? 16 : 12, strokeLinecap: 'round', strokeLinejoin: 'round' } as const;
  return (
    <>
      {duo && <path d={area} opacity={0.2} />}
      <path d={area} {...line} />
      <path d={lines} {...line} />
    </>
  );
}

type Props = { size?: number; className?: string; style?: CSSProperties } & ({ name: DuoIconName; weight?: IconWeight } | { name: IconName; weight?: 'light' });

export function Icon({ name, size, weight = 'light', className, style }: Props) {
  const cls = `mz-ic${DIRECTIONAL.has(name) ? ' mz-flip' : ''}${className ? ` ${className}` : ''}`;
  const duo = weight === 'duotone';
  let body;
  if (name in CUSTOM) body = <Drawn name={name as keyof typeof CUSTOM} duo={duo} />;
  else {
    const g: Glyph = GLYPHS[name as keyof G];
    body = (duo && g.duotone || g.light).map(([d, opacity], i) => <path key={i} d={d} opacity={opacity} />);
  }
  return (
    <svg className={cls} viewBox="0 0 256 256" width="1em" height="1em" fill="currentColor" aria-hidden="true" focusable="false"
      style={size ? { fontSize: size, ...style } : style}>
      {body}
    </svg>
  );
}
