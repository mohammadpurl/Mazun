-- Mazun Atelier schema. Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- Safe to run again: every statement is idempotent. Then load the starter catalogue with
-- `npm run seed:supabase` (it only fills empty tables).
--
-- Security model: the Next.js server talks to Supabase with the service-role key, which bypasses RLS.
-- RLS is ON with NO policies, so the public anon key can read or write nothing. Customer names and
-- phone numbers in "orders" are therefore never reachable from the browser.
--
-- Translated text is jsonb {"en": "...", "ar": "...", "fa": "..."}.

create table if not exists public.categories (
  id          text primary key default gen_random_uuid()::text,
  name        jsonb not null default '{}'::jsonb,
  description jsonb not null default '{}'::jsonb,
  image       text  not null default '',
  sort        int   not null default 0,
  visible     boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.garments (
  id          text primary key default gen_random_uuid()::text,
  kind        text not null default 'garment' check (kind in ('garment','scarf','bag','jewel','shoes')),
  category_id text references public.categories(id) on delete set null,
  name        jsonb not null default '{}'::jsonb,
  type        jsonb not null default '{}'::jsonb,
  description jsonb not null default '{}'::jsonb,
  fabric      jsonb not null default '{}'::jsonb,
  note        jsonb not null default '{}'::jsonb,          -- why the stylist picks this accessory
  price       numeric(10,3) not null default 0 check (price >= 0),
  sale_price  numeric(10,3) check (sale_price is null or sale_price >= 0),
  colors      jsonb not null default '[]'::jsonb,          -- [{"name":{...},"hex":"#6F7258"}]
  sizes       jsonb not null default '[]'::jsonb,          -- [{"n":"S","ok":true}]
  shape       text  not null default 'abaya' check (shape in ('abaya','gown','dress','kaftan')),
  front       text  not null default '',
  back        text  not null default '',
  detail      text  not null default '',
  chart       jsonb,                                       -- {"S":{"bust":86,...}}
  lead_days   int   not null default 0 check (lead_days >= 0),
  is_new      boolean not null default false,
  sort        int   not null default 0,
  visible     boolean not null default true,
  created_at  timestamptz not null default now()
);
create index if not exists garments_kind_idx on public.garments (kind);

create table if not exists public.orders (
  id            bigint generated by default as identity (start with 1001) primary key,
  items         jsonb not null,                            -- [{garmentId,name,size,color,qty,price}], snapshot at order time
  total         numeric(10,3) not null,
  customer_name text not null,
  phone         text not null,
  city          text not null default '',
  address       text not null default '',
  note          text not null default '',
  event_date    date,
  lang          text not null default 'en' check (lang in ('en','ar','fa')),
  status        text not null default 'new'
                check (status in ('new','confirmed','preparing','shipped','delivered','cancelled')),
  admin_note    text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists orders_created_idx on public.orders (created_at desc);

create table if not exists public.settings (
  id         int primary key default 1 check (id = 1),
  data       jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.categories enable row level security;
alter table public.garments   enable row level security;
alter table public.orders     enable row level security;
alter table public.settings   enable row level security;

-- Public image bucket: anyone may view images; only the server (service role) uploads.
insert into storage.buckets (id, name, public) values ('garments', 'garments', true)
on conflict (id) do nothing;
