-- Mezon shop schema. Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- Safe to run again: every statement is idempotent.
--
-- Security model: the Next.js server talks to Supabase with the service-role key, which bypasses RLS.
-- RLS is ON with NO policies, so the public anon key can read or write nothing. Customer names and
-- phone numbers in "orders" are therefore never reachable from the browser.

create table if not exists public.categories (
  id         bigint generated by default as identity primary key,
  name_fa    text not null default '',
  name_ar    text not null default '',
  name_en    text not null default '',
  sort       int  not null default 0,
  visible    boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.garments (
  id          bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name_fa     text not null default '',
  name_ar     text not null default '',
  name_en     text not null default '',
  desc_fa     text not null default '',
  desc_ar     text not null default '',
  desc_en     text not null default '',
  price       numeric(10,3) not null default 0 check (price >= 0),
  sale_price  numeric(10,3) check (sale_price is null or sale_price >= 0),
  sizes       jsonb not null default '[]'::jsonb,   -- [{"n":"S","ok":true}, ...]
  front       text not null default '',
  back        text not null default '',
  chart       jsonb,                                -- {"S":{"bust":92,"waist":80,"hips":98,"length":140}, ...}
  lead_days   int  not null default 0 check (lead_days >= 0),
  sort        int  not null default 0,
  visible     boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.orders (
  id            bigint generated by default as identity (start with 1001) primary key,
  garment_id    bigint references public.garments(id) on delete set null,
  garment_name  text not null,                      -- snapshot at order time
  size          text not null,
  price         numeric(10,3) not null,              -- snapshot at order time
  customer_name text not null,
  phone         text not null,
  city          text not null default '',
  address       text not null default '',
  note          text not null default '',
  event_date    date,
  lang          text not null default 'fa' check (lang in ('fa','ar','en')),
  status        text not null default 'new'
                check (status in ('new','confirmed','preparing','shipped','delivered','cancelled')),
  admin_note    text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists orders_created_idx on public.orders (created_at desc);

create table if not exists public.settings (
  id         int primary key default 1 check (id = 1),
  data       jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.categories enable row level security;
alter table public.garments   enable row level security;
alter table public.orders     enable row level security;
alter table public.settings   enable row level security;

-- Remove the policies of the old static site (it let the browser read garments and any signed-in user write them).
drop policy if exists "garments read"  on public.garments;
drop policy if exists "garments write" on public.garments;

-- Public image bucket: anyone may view images; only the server (service role) uploads.
insert into storage.buckets (id, name, public) values ('garments', 'garments', true)
on conflict (id) do nothing;
drop policy if exists "garment images write" on storage.objects;

